#!/usr/bin/env python3
"""Refresh this repo from the live printer and regenerate the upstream diffs.

  tools/sync.py                 pull config from the printer, scrub, regenerate diffs + tables
  tools/sync.py --no-pull       only regenerate diffs/tables from what is already in config/

Pulls ~/printer_data/config (cfg/conf/py/json/sh only, no backups) and the local
klipper-toolchanger diff over SSH, scrubs secrets and LAN addresses, then diffs every
file listed in tools/upstream.tsv against the exact upstream commit it was based on.

Printer address, SSH key and LAN-address placeholders come from tools/local.json (git-ignored;
copy tools/local.example.json).
"""
import difflib
import io
import json
import os
import re
import subprocess
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CFG = ROOT / "config"
DIFFS = ROOT / "upstream-diffs"
GEN = ROOT / "docs" / "generated"
CACHE = ROOT / ".cache" / "upstream"
LOCAL = json.loads((ROOT / "tools" / "local.json").read_text()) if (ROOT / "tools" / "local.json").exists() else {}
HOST = LOCAL.get("host", "pi@printer.local")
KEY = os.path.expanduser(LOCAL.get("ssh_key", "~/.ssh/id_ed25519"))
SSH = ["ssh", "-i", KEY, "-o", "ConnectTimeout=10", HOST]

# Never publish these. Applied to every pulled text file.
SECRET_RES = [
    (re.compile(r"github_pat_[A-Za-z0-9_]+"), "<redacted-token>"),
    (re.compile(r"(?im)^(\s*[\w.-]*(api_key|apikey|token|password|passwd|secret|private_key)\s*[:=]\s*)\S.*$"), r"\1<redacted>"),
]
LAN = LOCAL.get("lan_placeholders", {})  # {"<ip>": "<printer-ip>", ...}; any other private IP -> <lan-ip>
LAN_RE = re.compile(r"\b(?:10\.\d{1,3}|192\.168|172\.(?:1[6-9]|2\d|3[01]))\.\d{1,3}\.\d{1,3}\b(?![/\d])")
SKIP = re.compile(r"(\.bak|\.orig|backup|ShakeTune_results|/\.)")


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, **kw).stdout


def scrub(text):
    for rx, rep in SECRET_RES:
        text = rx.sub(rep, text)
    return LAN_RE.sub(lambda m: LAN.get(m.group(0), "<lan-ip>"), text)


def pull():
    find = ("cd ~/printer_data/config && find . -path ./config_backups -prune -o -path ./ShakeTune_results -prune "
            "-o -type f -size -2M \\( -name '*.cfg' -o -name '*.conf' -o -name '*.py' -o -name '*.json' -o -name '*.sh' \\) "
            "-print | grep -v -E '\\.bak|\\.orig|backup|/printer-[0-9_]+\\.cfg' | tar czf - -T -")
    data = run(SSH + [find])
    for p in CFG.rglob("*"):
        if p.is_file():
            p.unlink()
    n = 0
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tf:
        for m in tf.getmembers():
            name = m.name.lstrip("./")
            if not m.isfile() or SKIP.search("/" + name):
                continue
            out = CFG / name
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(scrub(tf.extractfile(m).read().decode("utf-8", "replace")))
            n += 1
    print(f"pulled {n} config files")
    # local modifications to the klipper-toolchanger plugin checkout
    diff = run(SSH + ["cd ~/klipper-toolchanger && git diff"]).decode()
    (ROOT / "patches" / "klipper-toolchanger" / "local-changes.diff").write_text(scrub(diff))
    # pinned versions of every component on the printer
    vers = run(SSH + ["for d in klipper klipper-toolchanger tapchanger Klipper-Adaptive-Meshing-Purging klipper-led_effect "
                      "klipper_tmc_autotune klippain_shaketune klipper_auto_speed moonraker moonraker-timelapse crowsnest katapult; do "
                      "[ -d ~/$d/.git ] && echo \"$d|$(git -C ~/$d remote get-url origin)|$(git -C ~/$d rev-parse --short HEAD)|"
                      "$(git -C ~/$d log -1 --format=%cs)|$(git -C ~/$d describe --tags --always 2>/dev/null)\"; done; "
                      "echo \"mainsail|$(cat ~/mainsail/release_info.json 2>/dev/null | tr -d '\\n ')\""]).decode()
    rows = ["| Component | Upstream | Commit | Commit date | Describe |", "|---|---|---|---|---|"]
    for line in vers.splitlines():
        parts = line.split("|")
        if parts[0] == "mainsail":
            rows.append(f"| mainsail | see docs/03-software.md | | | `{scrub(parts[1])[:120]}` |")
        elif len(parts) == 5:
            url = re.sub(r"https://[^@/]+@", "https://", parts[1])  # strip any embedded credentials
            rows.append(f"| {parts[0]} | {url} | `{parts[2]}` | {parts[3]} | {parts[4]} |")
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "versions.md").write_text("# Component versions on the printer (generated by tools/sync.py)\n\n" + "\n".join(rows) + "\n")


def upstream_file(url, rev, path):
    name = url.rstrip("/").split("/")[-2] + "__" + url.rstrip("/").split("/")[-1]
    repo = CACHE / name
    if not repo.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        run(["git", "clone", "-q", "--filter=blob:none", "--no-checkout", url, str(repo)])
    try:
        return run(["git", "-C", str(repo), "show", f"{rev}:{path}"]).decode("utf-8", "replace")
    except subprocess.CalledProcessError:
        run(["git", "-C", str(repo), "fetch", "-q", "origin"])
        return run(["git", "-C", str(repo), "show", f"{rev}:{path}"]).decode("utf-8", "replace")


def meaningful(lines):
    return [l.strip() for l in lines if l.strip() and not l.strip().startswith("#")]


def diffs():
    rows = []
    mapped = set()
    for line in (ROOT / "tools" / "upstream.tsv").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        boss, url, rev, path, note = line.split("\t")
        mapped.add(boss)
        mine = (CFG / boss).read_text().splitlines(keepends=True) if (CFG / boss).exists() else []
        theirs = upstream_file(url, rev, path).splitlines(keepends=True)
        d = list(difflib.unified_diff(theirs, mine, f"upstream/{path} @ {rev}", f"config/{boss}"))
        out = DIFFS / (boss + ".diff")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text("".join(d))
        added = sum(1 for l in d if l.startswith("+") and not l.startswith("+++"))
        removed = sum(1 for l in d if l.startswith("-") and not l.startswith("---"))
        sim = difflib.SequenceMatcher(None, meaningful(theirs), meaningful(mine), autojunk=False).ratio()
        repo = "/".join(url.rstrip("/").split("/")[-2:])
        rows.append(f"| `{boss}` | [{repo}]({url}) `{path}` @ `{rev}` | {sim:.0%} | +{added} / -{removed} | "
                    f"[diff](../../upstream-diffs/{boss.replace(' ', '%20')}.diff) | {note} |")
    own = sorted(str(p.relative_to(CFG)) for p in CFG.rglob("*.cfg") if str(p.relative_to(CFG)) not in mapped)
    md = ["# Upstream map (generated by tools/sync.py)", "",
          "Similarity ignores comments and blank lines. +/- counts are raw diff lines.", "",
          "| Config file | Based on | Same as upstream | Changed lines | Diff | What we changed |", "|---|---|---|---|---|---|"] + rows
    md += ["", "## Files with no upstream (written for this build, or printer-generated)", ""] + [f"- `{f}`" for f in own]
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "upstream-map.md").write_text("\n".join(md) + "\n")
    print(f"wrote {len(rows)} diffs, {len(own)} files without upstream")


if __name__ == "__main__":
    if "--no-pull" not in sys.argv:
        pull()
    diffs()
