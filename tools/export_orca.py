#!/usr/bin/env python3
"""Copy the slicer presets this build uses from the local (Snapmaker) Orca install into slicer/orca/.

The preset names are listed in tools/orca_presets.txt as <kind>/<name> (kind = machine,
filament or process). Each one only stores the settings that differ from the Orca system
preset it inherits from ("inherits" key), so slicer/orca/README.md records which Orca build
those system presets came from. The printer address is scrubbed.
"""
import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(os.path.expanduser(os.environ.get("ORCA_USER_DIR", "~/.config/Snapmaker_Orca/user/default")))
OUT = ROOT / "slicer" / "orca"
LAN_RE = re.compile(r"\b(?:10\.\d{1,3}|192\.168|172\.(?:1[6-9]|2\d|3[01]))\.\d{1,3}\.\d{1,3}\b(?![/\d])")
DROP = {"print_host", "printhost_apikey", "printhost_cafile", "print_host_webui", "printhost_password", "printhost_user"}

rows = []
for line in (ROOT / "tools" / "orca_presets.txt").read_text().splitlines():
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    kind, name = line.split("/", 1)
    data = json.loads((SRC / kind / f"{name}.json").read_text())
    for k in DROP & data.keys():
        data[k] = ""
    text = LAN_RE.sub("<printer-ip>", json.dumps(data, indent=4, ensure_ascii=False))
    (OUT / kind).mkdir(parents=True, exist_ok=True)
    (OUT / kind / f"{name}.json").write_text(text + "\n")
    rows.append(f"| {kind} | `{name}` | `{data.get('inherits', '')}` |")
    print("exported", kind, name)

(OUT / "presets.md").write_text("# Exported presets (generated by tools/export_orca.py)\n\n"
                                "| Kind | Preset | Inherits from (Orca system preset) |\n|---|---|---|\n" + "\n".join(rows) + "\n")
